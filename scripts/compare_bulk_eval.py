# scripts/compare_bulk_eval.py
"""Compare docs/moby-bulk-eval-raw.json against docs/moby-bulk-eval-initial.yaml.

Usage:
    python scripts/compare_bulk_eval.py

Reads:
  - docs/moby-bulk-eval-initial.yaml  (baseline classifications, per-question)
  - docs/moby-bulk-eval-raw.json      (new run, generated by scripts/moby_bulk_eval.py)

Writes:
  - docs/moby-bulk-eval-20260421-delta.md  (regression + improvement report)

Exit code:
  0 if no regressions on PASS_NOW items, 1 otherwise.
"""
from __future__ import annotations
import json, re, sys, pathlib
from typing import Optional

import yaml  # PyYAML, already a backend dep

ROOT = pathlib.Path(__file__).resolve().parents[1]
BASELINE_YAML = ROOT / "docs" / "moby-bulk-eval-initial.yaml"
RAW_JSON = ROOT / "docs" / "moby-bulk-eval-raw.json"
DELTA_MD = ROOT / "docs" / "moby-bulk-eval-20260421-delta.md"

_ROW_RE = re.compile(r"(\d+)\s*(?:row|site|countr|activit|institution|coordinator)", re.I)


def _expected_row_count(observed: str) -> Optional[int]:
    """Extract the first integer-like count from a baseline observed_behavior string.

    Examples:
      "79 rows, 3 countries correctly resolved" -> 79
      "37 rows — returned ALL sites" -> 37
      "2 sites (Augsburg 57km, Innsbruck 98km)" -> 2
    Returns None if no count is found.
    """
    if not observed:
        return None
    m = _ROW_RE.search(observed)
    return int(m.group(1)) if m else None


def classify(baseline: dict, raw: Optional[dict]) -> str:
    """Return one of: PRESERVED, REGRESSION, CANDIDATE_IMPROVEMENT, UNCHANGED, SKIPPED, MISSING."""
    if raw is None:
        return "MISSING"

    cat = baseline.get("category", "").upper()

    if cat == "AMBIGUOUS":
        return "SKIPPED"

    if cat in ("FUTURE_FEATURE",):
        return "UNCHANGED"

    if cat == "KNOWN_GAP":
        if raw.get("status") == "OK" and raw.get("has_table"):
            return "CANDIDATE_IMPROVEMENT"
        return "UNCHANGED"

    # PASS_NOW (default)
    if raw.get("status") != "OK":
        return "REGRESSION"
    expected = _expected_row_count(baseline.get("observed_behavior", ""))
    actual = int(raw.get("rows") or 0)
    if expected is not None and expected > 0 and actual > 0:
        if actual * 10 < expected:  # >1 order of magnitude drop
            return "REGRESSION"
    if expected is not None and expected > 0 and actual == 0:
        return "REGRESSION"
    return "PRESERVED"


def _load_baseline() -> dict[str, dict]:
    with open(BASELINE_YAML) as f:
        doc = yaml.safe_load(f) or {}
    entries = doc.get("entries") or []
    return {e["id"]: e for e in entries}


def _load_raw() -> dict[str, dict]:
    with open(RAW_JSON) as f:
        return {r["id"]: r for r in json.load(f)}


def main() -> int:
    baseline = _load_baseline()
    raw = _load_raw()

    buckets = {k: [] for k in
               ("PRESERVED", "REGRESSION", "CANDIDATE_IMPROVEMENT", "UNCHANGED", "SKIPPED", "MISSING")}
    for qid, b in baseline.items():
        cls = classify(b, raw.get(qid))
        buckets[cls].append((qid, b, raw.get(qid)))

    # Report
    lines = [
        "# Moby bulk-eval delta — 2026-04-21",
        "",
        f"Baseline: `docs/moby-bulk-eval-initial.yaml` (2026-03-25)",
        f"New run: `docs/moby-bulk-eval-raw.json`",
        "",
        "## Summary",
        "",
        f"- **Preserved (PASS_NOW still OK)**: {len(buckets['PRESERVED'])}",
        f"- **Regressions (PASS_NOW broken)**: {len(buckets['REGRESSION'])}",
        f"- **Candidate improvements (KNOWN_GAP now OK)**: {len(buckets['CANDIDATE_IMPROVEMENT'])}",
        f"- **Unchanged (KNOWN_GAP/FUTURE_FEATURE still as-is)**: {len(buckets['UNCHANGED'])}",
        f"- **Skipped (AMBIGUOUS)**: {len(buckets['SKIPPED'])}",
        f"- **Missing (no raw entry)**: {len(buckets['MISSING'])}",
        "",
    ]
    if buckets["REGRESSION"]:
        lines += ["## Regressions", ""]
        for qid, b, r in buckets["REGRESSION"]:
            lines.append(
                f"- **{qid}**: {b['question']!r} — baseline observed: {b.get('observed_behavior','?')!r}; "
                f"new: status={r.get('status')}, rows={r.get('rows')}, preview={r.get('answer_preview','')[:120]!r}"
            )
        lines.append("")
    if buckets["CANDIDATE_IMPROVEMENT"]:
        lines += ["## Candidate improvements (manual review)", ""]
        for qid, b, r in buckets["CANDIDATE_IMPROVEMENT"]:
            lines.append(
                f"- **{qid}**: {b['question']!r} — baseline: KNOWN_GAP ({b.get('observed_behavior','?')!r}); "
                f"new: rows={r.get('rows')}, preview={r.get('answer_preview','')[:120]!r}"
            )
        lines.append("")
    if buckets["MISSING"]:
        lines += ["## Missing (no raw entry)", ""]
        for qid, b, _ in buckets["MISSING"]:
            lines.append(f"- **{qid}**: {b['question']!r}")
        lines.append("")

    DELTA_MD.write_text("\n".join(lines))

    # Human echo
    for k in ("PRESERVED", "REGRESSION", "CANDIDATE_IMPROVEMENT", "UNCHANGED", "SKIPPED", "MISSING"):
        print(f"{k}: {len(buckets[k])}")

    return 1 if buckets["REGRESSION"] else 0


if __name__ == "__main__":
    sys.exit(main())
